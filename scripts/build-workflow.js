      Object.assign({ method: 'GET', url: "={{ $('Normalize Closed-Won Events').item.json.associationsUrl }}", options: { timeout: 15000, batching: { batch: { batchSize: 5, batchInterval: 1000 } } } }, hubspotAuth),
      { credentials: CREDENTIALS.hubspot, onError: 'continueRegularOutput', notes: 'v4 associations with labels; companies labelled PARTNER_ASSOCIATION_LABEL receive a partner carve-out.' }
